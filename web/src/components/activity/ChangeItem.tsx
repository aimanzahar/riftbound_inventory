export interface FeedLine {
  card_id: string;
  finish?: Finish;
  qty?: number;
  prev_qty?: number;
  note?: string;
  prev_note?: string;
  clamped?: true;
}

/** Lines worth expanding for a change (empty for system rows). */
export function linesOf(c: Change): FeedLine[] {
  if (c.kind === 'inventory') return (c.payload as InventoryPayload).lines;
  if (c.kind === 'tip') return [{ card_id: (c.payload as TipPayload).card_id }];
  return [];
}

const HOVER_DELAY = 120;
const LINE_CAP = 40;

/** One card line: thumb + name + finish + prev → new. Click → drawer; hover/focus → HoverPreview; long-press → sheet. */
function LineRow({ line }: { line: FeedLine }) {
  const card = useCard(line.card_id);
  const show = usePreview((s) => s.show);
  const hide = usePreview((s) => s.hide);
  const openSheet = usePreview((s) => s.openSheet);
  const ref = useRef<HTMLButtonElement>(null);
  const thumbRef = useRef<HTMLSpanElement>(null);
  const hoverTimer = useRef<number | null>(null);

  const clearHover = useCallback(() => {
    if (hoverTimer.current !== null) window.clearTimeout(hoverTimer.current);
    hoverTimer.current = null;
  }, []);
  useEffect(() => clearHover, [clearHover]);

  const anchor = () => thumbRef.current ?? ref.current;
  const onPointerEnter = (e: ReactPointerEvent<HTMLElement>) => {
    if (e.pointerType !== 'mouse' || !card) return;
    void preload(card, 'full');
    clearHover();
    hoverTimer.current = window.setTimeout(() => {
      hoverTimer.current = null;
      const el = anchor();
      if (el) show(line.card_id, rectOf(el), 'mouse');
    }, HOVER_DELAY);
  };
  const onPointerLeave = (e: ReactPointerEvent<HTMLElement>) => {
    if (e.pointerType !== 'mouse') return;
    clearHover();
    hide(line.card_id);
  };
  const onFocus = (e: FocusEvent<HTMLElement>) => {
    if (e.target !== ref.current || !card) return;
    const el = anchor();
    if (el && ref.current.matches(':focus-visible')) show(line.card_id, rectOf(el), 'focus');
  };
  const longPress = useLongPress(() => {
    clearHover();
    openSheet(line.card_id);
  });

  const name = card?.name ?? line.card_id;
  const foil = line.finish === 'foil';
  const hasQty = line.qty !== undefined && line.prev_qty !== undefined;
  const delta = hasQty ? (line.qty as number) - (line.prev_qty as number) : 0;
  const noteChanged = line.prev_note !== undefined && line.prev_note !== line.note;
  const label = `${name}${foil ? ' foil' : ''}${hasQty ? `, ${line.prev_qty} to ${line.qty}` : ''} — open card`;

  return (
    <li>
      <button
        ref={ref}
        type="button"
        aria-label={label}
        onClick={() => {
          clearHover();
          hide(line.card_id);
          openCard(line.card_id);
        }}
        {...longPress}
        onPointerEnter={onPointerEnter}
        onPointerLeave={(e) => {
          longPress.onPointerLeave(e);
          onPointerLeave(e);
        }}
        onFocus={onFocus}
        onBlur={(e) => e.target === ref.current && hide(line.card_id)}
        className="tile flex min-h-10 w-full items-center gap-2.5 rounded-lg px-1.5 py-1 text-left outline-none transition-colors hover:bg-surface-2 focus-visible:bg-surface-2 focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-accent/40 pointer-coarse:min-h-11"
      >
        <span ref={thumbRef} data-thumb className="block w-7 shrink-0">
          {card ? <CardImage card={card} kind="thumb" rounded="rounded" /> : <span className="block aspect-[5/7] w-full rounded bg-surface-3" aria-hidden />}
        </span>
        <span className="min-w-0 flex-1">
          <span className="block truncate text-[13px] font-medium leading-[17px] text-fg">{name}</span>
          <span className="block truncate text-[11px] leading-4 text-muted">
            <span className="tabular">{line.card_id}</span>
            {foil && <span className="foil-text ml-1.5 font-semibold">✦ foil</span>}
            {line.clamped && <span className="ml-1.5 text-warning">· clamped at 0</span>}
            {noteChanged && <span className="ml-1.5 italic">· note {line.note ? `“${line.note}”` : 'cleared'}</span>}
          </span>
        </span>
        {hasQty && (
          <span className="tabular flex shrink-0 items-center gap-1 text-[12.5px]">
            <span className="text-muted">{line.prev_qty}</span>
            <span className="text-faint" aria-hidden>
              →
            </span>
            <span className="font-semibold text-fg">{line.qty}</span>
            <span className={cx('ml-1 min-w-6 text-right font-semibold', delta > 0 ? 'text-success' : delta < 0 ? 'text-danger' : 'text-faint')}>{delta === 0 ? '·' : signed(delta)}</span>
          </span>
        )}
      </button>
    </li>
  );
}

function Lines({ lines, id }: { lines: FeedLine[]; id: string }) {
  const [all, setAll] = useState(false);
  const visible = all ? lines : lines.slice(0, LINE_CAP);
  return (
    <ol id={id} className="mt-1 flex flex-col" aria-label="Cards in this change">
      {visible.map((l, i) => (
        <LineRow key={`${l.card_id}:${l.finish ?? ''}:${i}`} line={l} />
      ))}
      {lines.length > visible.length && (
        <li>
          <button type="button" onClick={() => setAll(true)} className="mt-1 inline-flex min-h-8 items-center rounded-md px-1.5 text-xs font-medium text-accent hover:bg-accent/10 pointer-coarse:min-h-11">
            Show all {pluralize(lines.length, 'card')}
          </button>
        </li>
      )}
    </ol>
  );
}

