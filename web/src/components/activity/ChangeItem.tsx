function ActorDot({ device }: { device: Change['device'] }) {
  if (device) return <Avatar name={device.name} color={device.color} size="sm" className="mt-0.5" />;
  return (
    <span role="img" aria-label="System" title="System" className="mt-0.5 inline-flex size-7 shrink-0 items-center justify-center rounded-full border border-border bg-surface-2 text-muted">
      <Cpu className="size-3.5" aria-hidden />
    </span>
  );
}

/** Secondary detail under the summary for non-card changes. */
function Detail({ change }: { change: Change }) {
  if (change.kind === 'tip') {
    const p = change.payload as TipPayload;
    return p.text ? <p className="mt-1 line-clamp-2 text-[12.5px] italic leading-snug text-muted">“{p.text}”</p> : null;
  }
  if (change.kind === 'settings') {
    const p = change.payload as SettingsPayload;
    return (
      <p className="tabular mt-1 text-[12px] leading-snug text-muted">
        playset {p.playset_size} · rune playset {p.rune_playset_size}
        {p.fx_manual_rate !== null ? ` · manual FX ${p.fx_manual_rate}` : ''}
        {p.collection_name ? ` · “${p.collection_name}”` : ''}
      </p>
    );
  }
  return null;
}

export interface ChangeItemProps {
  change: Change;
  /** Date.now() snapshot shared by the feed (relative times refresh together) */
  now: number;
  /** this row was made by the current device */
  mine: boolean;
  /** an undo for this row is in flight */
  busy: boolean;
  /** briefly emphasised after a jump */
  highlighted?: boolean;
  onUndo: (seq: number) => void;
  onJump: (seq: number) => void;
}

function ChangeItemInner({ change: c, now, mine, busy, highlighted, onUndo, onJump }: ChangeItemProps) {
  const cardsById = useStore((s) => s.cardsById);
  const [open, setOpen] = useState(false);
  const linesId = useId();

  const who = c.device?.name ?? 'System';
  const { text } = changeSummary(c, (id) => cardsById.get(id));
  // the actor is already shown in the header — drop the leading name from the one-liner
  const body = text.startsWith(`${who} `) ? text.slice(who.length + 1) : text;
  const kind = kindOf(c);
  const lines = linesOf(c);
  const canUndo = c.kind === 'inventory' && !c.undone;

  return (
    <li
      id={`change-${c.seq}`}
      data-seq={c.seq}
      aria-label={`#${c.seq}: ${text}`}
      className={cx('relative flex gap-3 px-3 py-2.5 transition-colors duration-300 sm:px-4', c.undone && 'opacity-60', highlighted && 'bg-accent/10')}
    >
      <ActorDot device={c.device} />
      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-x-2 gap-y-1 text-[12px] leading-5 text-muted">
          <span className="font-semibold text-fg">{who}</span>
          {mine && <span className="text-faint">(you)</span>}
          <Badge tone={KIND_TONE[kind]} size="xs" title={KIND_TITLE[kind]}>
            {kind}
          </Badge>
          {c.undone && (
            <Badge tone="outline" size="xs" title="This change was undone">
              undone
            </Badge>
          )}
          {c.undo_of !== null && (
            <button
              type="button"
              onClick={() => onJump(c.undo_of as number)}
              title={`Jump to change #${c.undo_of}`}
              className="inline-flex items-center gap-1 rounded-md px-1 text-[11.5px] text-accent hover:bg-accent/10 hover:text-accent-strong pointer-coarse:-my-3 pointer-coarse:min-h-11"
            >
              <CornerUpLeft className="size-3" aria-hidden />
              undo of #{c.undo_of}
            </button>
          )}
          <time dateTime={c.ts} title={`${fmtDateTime(c.ts)} · #${c.seq}`} className="tabular ml-auto shrink-0 text-[11.5px] text-faint">
            {relTime(c.ts, now)}
          </time>
        </div>
        <p className={cx('mt-0.5 text-[13.5px] leading-snug text-fg', c.undone && 'line-through decoration-faint')}>{body}</p>
        <Detail change={c} />
        {lines.length > 0 && (
          <div className="mt-1">
            <button
              type="button"
              aria-expanded={open}
              aria-controls={linesId}
              onClick={() => setOpen((o) => !o)}
              className="-ml-1 inline-flex min-h-7 items-center gap-1 rounded-md px-1 text-[12px] text-muted hover:bg-surface-2 hover:text-fg pointer-coarse:min-h-11"
            >
              <ChevronRight className={cx('size-3.5 transition-transform duration-150', open && 'rotate-90')} aria-hidden />
              {c.kind === 'tip' ? 'Show card' : pluralize(lines.length, 'card')}
            </button>
            {open && <Lines lines={lines} id={linesId} />}
          </div>
        )}
      </div>
      {canUndo && (
        <Button
          variant="ghost"
          size="sm"
          leftIcon={<Undo2 className="size-3.5" aria-hidden />}
          loading={busy}
          disabled={busy}
          onClick={() => onUndo(c.seq)}
          aria-label={`Undo change #${c.seq}`}
          className="-mr-1 self-start pointer-coarse:h-11 pointer-coarse:px-3"
        >
          Undo
        </Button>
      )}
    </li>
  );
}

export const ChangeItem = memo(ChangeItemInner);
